// ============================================================
// 第一课：基本类型 — TypeScript 与 JS 最大的不同
// ============================================================
// JS：变量可以随便换类型，运行时才发现错误
// TS：给变量加"类型标签"，写代码时就报错

// -------------------------------------------------------
// 1. 类型注解 (Type Annotation)
// -------------------------------------------------------
// 语法：变量名: 类型 = 值
// 这个 : 后面的就是类型注解

let name1: string = "being";
let age: number = 22;
let isStudent: boolean = true;

// ❌ 这样会报错（试着去掉注释看看）：
// name1 = 123;        // 不能把 number 赋给 string
// age = "二十二";      // 不能把 string 赋给 number

// -------------------------------------------------------
// 2. 类型推断 (Type Inference)
// -------------------------------------------------------
// 大部分时候不需要写类型，TS 自己能猜出来

let name2 = "being";   // TS 推断为 string
let score = 100;       // TS 推断为 number

// name2 = 456;  // ❌ TS 记得 name2 是 string

// 什么时候必须写类型注解？
// - 函数参数
// - 声明时不赋值的情况
let futureValue: string;  // 必须写，因为没初始值

// -------------------------------------------------------
// 3. 数组 (Array)
// -------------------------------------------------------
// 两种写法，效果一样

let numbers1: number[] = [1, 2, 3];
let numbers2: Array<number> = [1, 2, 3];  // 泛型写法，后面讲

let names: string[] = ["张三", "李四"];

// 混合类型数组 — 用联合类型
let mixed: (string | number)[] = ["abc", 123, "def"];

// -------------------------------------------------------
// 4. 对象 (Object)
// -------------------------------------------------------

let user: {
  name: string;
  age: number;
  email?: string;  // ? 表示可选属性
} = {
  name: "being",
  age: 22,
  // email 可以不写，因为标记了 ?
};

// user.name = 123;  // ❌ 类型不匹配
user.name = "being221";  // ✅

// -------------------------------------------------------
// 5. any — 逃生门
// -------------------------------------------------------
// any 就是关掉类型检查，回归 JS 行为
// 💡 尽量少用，否则失去 TS 的意义

let anything: any = "hello";
anything = 42;       // ✅ 不报错
anything = [1, 2];   // ✅ 不报错
anything.foo.bar();  // ✅ 不报错（但运行时可能崩）

// -------------------------------------------------------
// 6. 字面量类型 (Literal Type)
// -------------------------------------------------------
// 把具体的值当作类型

let direction: "left" | "right" | "up" | "down";
direction = "left";   // ✅
// direction = "forward";  // ❌ 不在允许值里面

let httpStatus: 200 | 404 | 500 = 200;

// -------------------------------------------------------
// 7. 枚举 (Enum) — 给一组值起名字
// -------------------------------------------------------

enum Theme {
  Dark = "dark",
  Light = "light",
  Auto = "auto",
}

let currentTheme: Theme = Theme.Dark;

// -------------------------------------------------------
// 练习区
// -------------------------------------------------------
// 把下面的 JS 代码改成带类型的 TS 代码：

// 原 JS：
// let items = ["apple", "banana", "orange"];
// let prices = [5, 3, 8];
// let config = { title: "我的网站", version: 1 };

// 你的 TS 版本：
let items: string[] = ["apple", "banana", "orange"];
let prices: number[] = [5, 3, 8];
let config: { title: string; version: number } = {
  title: "我的网站",
  version: 1,
};

console.log("✅ 第一课完成！运行 npx tsc --noEmit 检查类型");

export {};
